function mirrorX(x: number): number {
  return Math.round((MOUNTAIN_VIEWBOX_WIDTH - x) * 100) / 100;
}

function serializePathCommands(
  commands: readonly PathCommand[],
  mirrorHorizontal: boolean
): string {
  return commands
    .map((cmd) => {
      switch (cmd[0]) {
        case "M":
        case "L": {
          const x = mirrorHorizontal ? mirrorX(cmd[1]) : cmd[1];
          return `${cmd[0]} ${x} ${cmd[2]}`;
        }
        case "Q": {
          const x1 = mirrorHorizontal ? mirrorX(cmd[1]) : cmd[1];
          const x = mirrorHorizontal ? mirrorX(cmd[3]) : cmd[3];
          return `Q ${x1} ${cmd[2]}, ${x} ${cmd[4]}`;
        }
        case "C": {
          const x1 = mirrorHorizontal ? mirrorX(cmd[1]) : cmd[1];
          const x2 = mirrorHorizontal ? mirrorX(cmd[3]) : cmd[3];
          const x = mirrorHorizontal ? mirrorX(cmd[5]) : cmd[5];
          return `C ${x1} ${cmd[2]}, ${x2} ${cmd[4]}, ${x} ${cmd[6]}`;
        }
        case "Z":
          return "Z";
      }
    })
    .join(" ");
}

/**
 * Builds the pure SVG path geometry for a multi-peak Hokkaido alpine range and valley flank,
 * mirroring horizontal ridge coordinates on the right flank while preserving upper-left sun direction.
 */
export function buildMountainCardProfile(
  kind: MountainPeakKind,
  flank: MountainValleyFlank
): MountainCardProfile {
  if (!Object.hasOwn(RANGE_TEMPLATES, kind)) {
    throw new Error(`Unsupported mountain peak kind: ${String(kind)}`);
  }
  if (flank !== "left" && flank !== "right") {
    throw new Error(`Unsupported mountain valley flank: ${String(flank)}`);
  }

  const mirrorHorizontal = flank === "right";
  const template = RANGE_TEMPLATES[kind];
  const sunlitCommands = mirrorHorizontal ? template.eastFaces : template.westFaces;
  const shadedCommands = mirrorHorizontal ? template.westFaces : template.eastFaces;

  return {
    kind,
    flank,
    peakCount: template.peakCount,
    viewBox: MOUNTAIN_VIEWBOX,
    backRangePath: serializePathCommands(template.backRange, mirrorHorizontal),
    silhouettePath: serializePathCommands(template.silhouette, mirrorHorizontal),
    sunlitFacesPath: serializePathCommands(sunlitCommands, mirrorHorizontal),
    shadedFacesPath: serializePathCommands(shadedCommands, mirrorHorizontal),
    areteRidgesPath: serializePathCommands(template.areteRidges, mirrorHorizontal),
  };
}

/**
 * Resolves the multi-peak Hokkaido alpine silhouette profile for a proposal waypoint index,
 * cycling through eight distinct (range, flank) combinations so every stop has a unique skyline.
 */
export function getMountainCardProfile(waypointIndex: number): MountainCardProfile {
  if (!Number.isInteger(waypointIndex) || waypointIndex < 0) {
    throw new Error("waypointIndex must be a non-negative integer");
  }

  const kind = WAYPOINT_RANGE_CYCLE[waypointIndex % WAYPOINT_RANGE_CYCLE.length];
  const flank: MountainValleyFlank = waypointIndex % 2 === 0 ? "left" : "right";

  return buildMountainCardProfile(kind, flank);
}
