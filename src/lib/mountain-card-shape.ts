export type MountainPeakKind =
  | "daisetsuzan-massif"
  | "niseko-traverse"
  | "shiretoko-horns"
  | "tokachi-ridge";

export type MountainValleyFlank = "left" | "right";

export interface MountainCardProfile {
  readonly kind: MountainPeakKind;
  readonly flank: MountainValleyFlank;
  readonly peakCount: number;
  readonly viewBox: string;
  readonly backRangePath: string;
  readonly silhouettePath: string;
  readonly sunlitFacesPath: string;
  readonly shadedFacesPath: string;
  readonly areteRidgesPath: string;
}

type PathCommand =
  | readonly ["M", number, number]
  | readonly ["L", number, number]
  | readonly ["Q", number, number, number, number]
  | readonly ["C", number, number, number, number, number, number]
  | readonly ["Z"];

interface RangeTemplate {
  readonly kind: MountainPeakKind;
  readonly peakCount: number;
  readonly backRange: readonly PathCommand[];
  readonly silhouette: readonly PathCommand[];
  readonly westFaces: readonly PathCommand[];
  readonly eastFaces: readonly PathCommand[];
  readonly areteRidges: readonly PathCommand[];
}

